#!/usr/bin/env python3
"""Generate tiny, exact-file-gated patch recipes for one firmware release.

The firmware is a captured /system, or a compatibility log's system/ folder (which has the
ODEX but not the APKs: pass their hashes from its tilepad-compat.txt with --compat-log).
Only offsets, changed instructions and hashes ship. No OEM APK/ODEX is bundled.
Consent and nav operations are derived from the local Cabinwright MIT patches.
"""
import argparse
import hashlib
import re
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


class Dex:
    def __init__(self, source):
        self.source = source
        if source[:8] != b"dey\n036\0":
            raise ValueError("Expected ODEX 036")
        self.start, self.size = struct.unpack_from("<II", source, 8)
        self.data = source[self.start:self.start + self.size]
        if self.data[:8] != b"dex\n035\0" or zlib.adler32(self.data[12:]) != self.u4(8):
            raise ValueError("Bad optimized DEX checksum")
        count, table = struct.unpack_from("<II", self.data, 56)
        self.strings = []
        for i in range(count):
            _, at = self.uleb(self.u4(table + i * 4))
            self.strings.append(self.data[at:self.data.index(0, at)].decode())
        count, table = struct.unpack_from("<II", self.data, 64)
        self.types = [self.strings[self.u4(table + i * 4)] for i in range(count)]
        count, table = struct.unpack_from("<II", self.data, 72)
        self.protos = []
        for i in range(count):
            _, result, params = struct.unpack_from("<III", self.data, table + i * 12)
            args = [] if params == 0 else [self.types[struct.unpack_from("<H", self.data, params + 4 + j * 2)[0]] for j in range(self.u4(params))]
            self.protos.append("(" + "".join(args) + ")" + self.types[result])
        count, table = struct.unpack_from("<II", self.data, 88)
        self.methods = []
        for i in range(count):
            owner, proto, name = struct.unpack_from("<HHI", self.data, table + i * 8)
            self.methods.append((self.types[owner], self.strings[name], self.protos[proto]))
        self.code = {}
        count, table = struct.unpack_from("<II", self.data, 96)
        for i in range(count):
            at = self.u4(table + i * 32 + 24)
            if not at:
                continue
            sizes = []
            for _ in range(4):
                n, at = self.uleb(at)
                sizes.append(n)
            for _ in range(sizes[0] + sizes[1]):
                _, at = self.uleb(at)
                _, at = self.uleb(at)
            for size in sizes[2:]:
                index = 0
                for _ in range(size):
                    diff, at = self.uleb(at)
                    index += diff
                    _, at = self.uleb(at)
                    code, at = self.uleb(at)
                    if code:
                        self.code[self.methods[index]] = self.start + code + 16

    def u4(self, at):
        return struct.unpack_from("<I", self.data, at)[0]

    def uleb(self, at):
        n = 0
        for shift in range(0, 35, 7):
            b = self.data[at]
            at += 1
            n |= (b & 127) << shift
            if b < 128:
                return n, at
        raise ValueError("Bad ULEB")

    def method(self, owner, name, proto):
        return self.code[(owner, name, proto)]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def check_md5(data, expected):
    if hashlib.md5(data).hexdigest() != expected:
        raise ValueError("Capture differs from supported stock file")


# Stock MD5 of each release's patched files, as checked when its recipes were made.
RELEASES = {
    "v015": {"RightScreenHome": "a46717495f957dab68b96cf6c9a01d4a", "SystemUI": "2363d6315a05b51064821b8beab7b5fd"},
    "v016": {"RightScreenHome": "4789932842938078386a21aecc77c984", "SystemUI": "3fba390d4485277ab882bff1d006fc55"},
    "kia-v015": {"RightScreenHome": "8c06f56597970d09ab369cfd8cc8c28d", "SystemUI": "8abb72b9715bc8e4746ac9ee3b03ab39"},
}


def apk_sha(firmware, path, apk_hashes):
    apk = firmware / path.removeprefix("/system/")
    return sha(apk.read_bytes()) if apk.is_file() else apk_hashes[path]


def write_recipe(out, name, release, path, apk_path, apk_sha256, stock, groups):
    dex = Dex(stock)
    lines = [f"# Exact stock file of firmware {release}; generated by firmware_patches.py",
             "path=" + path, "apkPath=" + apk_path, "apkSha256=" + apk_sha256,
             "stockSha256=" + sha(stock), "dexOffset=" + str(dex.start), "dexSize=" + str(dex.size)]
    for feature, operations in groups.items():
        lines.append(feature + "=" + ";".join(f"{at},{before.hex()},{after.hex()}" for at, before, after in operations))
        for at, before, after in operations:
            assert len(before) == len(after) and stock[at:at + len(before)] == before
    out.mkdir(parents=True, exist_ok=True)
    (out / name).write_text("\n".join(lines) + "\n")


def generate(firmware, out, release, apk_hashes=None):
    apk_hashes = apk_hashes or {}
    app = firmware / "app"
    stock = (app / "RightScreenHome.odex").read_bytes()
    check_md5(stock, RELEASES[release]["RightScreenHome"])
    dex = Dex(stock)
    owner = "Lcom/mobis/splitscreen/right/k/r;"
    nav_at = dex.method(owner, "f", "(ZZ)Z")
    nav = [(nav_at + 0x39 * 2, bytes.fromhex("33174000"), bytes.fromhex("29004000")),
           (nav_at + 0x5b * 2, bytes.fromhex("38070300"), bytes.fromhex("29000300"))]
    # Gate all standard OSD requests, then block the shared OSD entry and renderer
    # as well, including callers which bypass canShowSSOsd (e.g. forced OSDs).
    at = dex.method(owner, "canShowSSOsd", "(ZZZ)Z")
    popover = [(at, stock[at:at + 4], bytes.fromhex("12000f00"))]
    osd = "Lcom/mobis/splitscreen/right/r/i;"
    at = dex.method(osd, "d", "(IIZ)V")
    assert stock[at:at + 4] == bytes.fromhex("13081900")
    popover.append((at, stock[at:at + 4], bytes.fromhex("0e000000")))
    at = dex.method(osd, "handleShow", "()V")
    assert stock[at:at + 2] == bytes.fromhex("1200")
    popover.append((at, stock[at:at + 2], bytes.fromhex("0e00")))
    write_recipe(out, f"right-{release}.properties", release, "/system/app/RightScreenHome.odex", "/system/app/RightScreenHome.apk",
                 apk_sha(firmware, "/system/app/RightScreenHome.apk", apk_hashes), stock, {"nav": nav, "popover": popover})

    app = firmware / "priv-app"
    stock = (app / "SystemUI.odex").read_bytes()
    check_md5(stock, RELEASES[release]["SystemUI"])
    dex = Dex(stock)
    method = ("Lcom/android/systemui/consentscreen/D;", "dc", "()V")
    index = dex.methods.index(method)
    anchor = bytes.fromhex("f8200f00450029002dff")
    assert stock.count(anchor) == 1
    at = stock.index(anchor)
    before = stock[at:at + 6]
    after = bytes.fromhex("7010") + struct.pack("<H", index) + bytes.fromhex("0500")
    consent = [(at, before, after)]
    # ACC/profile/force-show broadcasts call T(I) too. Replace its construction
    # entry with the same agreement path, so later requests cannot recreate it.
    at = dex.method("Lcom/android/systemui/consentscreen/D;", "T", "(I)V")
    assert stock[at:at + 6] == bytes.fromhex("1204f4500c00")
    # Keep the original call address and its GC/register-map entry. The two
    # prefix instructions only initialize v4 and load Context into v0. Replace
    # getPackageManager + move-result with agreed + return, with no orphaned
    # move-result and no newly introduced invocation/program-counter location.
    at += 6
    assert stock[at:at + 8] == bytes.fromhex("f810390000000c00")
    consent.append((at, stock[at:at + 8], bytes.fromhex("7010") + struct.pack("<H", index) + bytes.fromhex("05000e00")))
    write_recipe(out, f"consent-{release}.properties", release, "/system/priv-app/SystemUI.odex", "/system/priv-app/SystemUI.apk",
                 apk_sha(firmware, "/system/priv-app/SystemUI.apk", apk_hashes), stock, {"consent": consent})

    # The track swap edits the key 34/35 lines every model's layout shares, so its
    # recipe names no file: the runtime targets the layouts the car loaded.
    for path in sorted((firmware / "usr/keylayout").glob("daudio_*_base.kl")):
        text = path.read_text()
        assert len(re.findall(r"(?m)^key\s+34\s+CHANNEL_UP\b", text)) == 1, path
        assert len(re.findall(r"(?m)^key\s+35\s+CHANNEL_DOWN\b", text)) == 1, path
    (out / "tracks.properties").write_text("kind=tracks\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("firmware", type=Path, help="A captured /system, or a compatibility log's system/ folder")
    parser.add_argument("release", choices=sorted(RELEASES), help="Which release it is (names the recipes)")
    parser.add_argument("--compat-log", type=Path, help="tilepad-compat.txt, for APK hashes the folder lacks")
    parser.add_argument("--out", type=Path, default=ROOT / "tune-service/tweaks/patches")
    args = parser.parse_args()
    hashes = {}
    if args.compat_log:
        for line in args.compat_log.read_text().splitlines():
            key, _, value = line.partition("=")
            if key.endswith(".apk"):
                hashes[key] = value
    generate(args.firmware, args.out, args.release, hashes)
